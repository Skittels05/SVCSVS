const { DataTypes } = require('sequelize');

module.exports = (sequelize) => {
  const RecoveryToken = sequelize.define('RecoveryToken', {
    id: {
      type: DataTypes.INTEGER,
      autoIncrement: true,
      primaryKey: true,
    },
    user_id: {
      type: DataTypes.INTEGER,
      allowNull: false,
      references: {
        model: 'users',
        key: 'id',
      },
      onDelete: 'CASCADE',
    },
    token: {
      type: DataTypes.STRING(255),
      allowNull: false,
      unique: true,
    },
    expires_at: {
      type: DataTypes.DATE,
      allowNull: false,
    },
    used: {
      type: DataTypes.BOOLEAN,
      defaultValue: false,
    },
    created_at: {
      type: DataTypes.DATE,
      defaultValue: DataTypes.NOW,
    },
  }, {
    tableName: 'recovery_tokens',
    timestamps: false,
    indexes: [
      { fields: ['token'] },
      { fields: ['expires_at'] },
    ],
  });

  return RecoveryToken;
};